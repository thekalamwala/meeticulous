-- v3.100_opening_ceremony.sql — "The Opening" launch event.
-- Idempotent. Apply on BOTH DBs (prod Mumbai ayjhlwyzszykqtnaktpb + staging Tokyo xwvciqkayammbvsidqig).
--
-- Visitors "cut the ribbon" during a ~24h window (Independence Day, 15→16 Aug)
-- and place a permanent named stone on the public Inaugurators Wall. One row per
-- opener. RLS on, no policies, service_role only — every read/write goes through
-- the server (supabaseAdmin); the public wall is served by our API, never anon.
--
--   number   hidden ordering key (identity). NEVER shown to users — gaps are fine.
--   name     shown on the stone.
--   message  optional line on the stone.
--   shade    stone colour variant index (brand palette), chosen at insert.
--   shape    stone SVG variant index, chosen at insert.
--   phone / verified / verified_at   PHASE 2 (WhatsApp verify) — unused in phase 1.
--
-- Additive; code keeps a schema fallback until applied on both DBs.

CREATE TABLE IF NOT EXISTS openers (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  number       BIGINT GENERATED BY DEFAULT AS IDENTITY,   -- hidden ordering; gaps OK
  name         TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  message      TEXT CHECK (char_length(message) <= 80),
  shade        SMALLINT NOT NULL DEFAULT 0,
  shape        SMALLINT NOT NULL DEFAULT 0,
  -- phase 2 (columns exist now, unused in phase 1):
  phone        TEXT,
  verified     BOOLEAN NOT NULL DEFAULT false,
  verified_at  TIMESTAMPTZ,
  -- provenance / anti-abuse:
  ip           INET,
  user_agent   TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS openers_number_idx ON openers (number);
-- one verified opener per phone (partial: unverified/null excluded) — phase 2.
CREATE UNIQUE INDEX IF NOT EXISTS openers_phone_uidx ON openers (phone) WHERE phone IS NOT NULL;

ALTER TABLE openers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON openers FROM anon, authenticated;

-- Event window (admin-adjustable). Default: 20 Aug 2026 12:15 IST → 23 Aug 2026 10:00 IST
-- (06:45 → 04:30 UTC). JSONB string values, like every other platform_settings row.
-- ON CONFLICT DO NOTHING so a later admin edit is never clobbered by re-running this.
INSERT INTO platform_settings (key, value) VALUES
  ('opening_opens_at',  '"2026-08-20T06:45:00Z"'),
  ('opening_closes_at', '"2026-08-23T04:30:00Z"')
ON CONFLICT (key) DO NOTHING;
